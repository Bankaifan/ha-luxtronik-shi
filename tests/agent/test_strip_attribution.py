import importlib.util
import json
import pathlib
import subprocess

_path = pathlib.Path(__file__).parent.parent.parent / "tools" / "strip_attribution.py"
_spec = importlib.util.spec_from_file_location("strip_attribution", _path)
mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mod)

CC = "_Generated by [Claude Code](https://claude.ai/code)_"
ENV = {"GH_REPO": "o/r"}


def fake_gh(monkeypatch, body, fail=False):
    calls = []

    def _run(cmd, **kw):
        calls.append((cmd, kw.get("input")))
        if fail:
            raise subprocess.CalledProcessError(1, cmd)
        return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps({"body": body}), stderr="")

    monkeypatch.setattr(mod.subprocess, "run", _run)
    return calls


def test_footer_is_removed_and_saved(monkeypatch):
    calls = fake_gh(monkeypatch, f"Closes #1\n\n---\n{CC}")
    assert mod.main(["7"], ENV) == 0
    assert calls[0][0] == ["gh", "api", "repos/o/r/issues/7"]
    assert calls[1][0] == ["gh", "api", "-X", "PATCH", "repos/o/r/issues/7", "-F", "body=@-"]
    assert calls[1][1] == "Closes #1\n"


def test_clean_body_is_not_edited(monkeypatch):
    for body in ("Closes #1\n\n---\nnotes", "", None):
        calls = fake_gh(monkeypatch, body)
        assert mod.main(["7"], ENV) == 0
        assert len(calls) == 1  # read only: no write, so no edited-event loop


def test_stripped_body_is_a_fixed_point(monkeypatch):
    calls = fake_gh(monkeypatch, f"a\n\n---\n{CC}")
    mod.main(["7"], ENV)
    calls = fake_gh(monkeypatch, calls[1][1])
    assert mod.main(["7"], ENV) == 0 and len(calls) == 1


def test_gh_error_and_usage(monkeypatch):
    fake_gh(monkeypatch, "x", fail=True)
    assert mod.main(["7"], ENV) == 1
    assert mod.main([], ENV) == 2
    assert mod.main(["x"], ENV) == 2


def test_long_pr_title_is_cut_at_a_word(monkeypatch):
    """#624: a fix run cannot edit a title; a script cuts it so check_pr_form passes."""
    long = "Pipeline canary: signed haiku issue after workflow/tools merges, 45 min check names the stalled stage x"
    calls = []

    def _run(cmd, **kw):
        calls.append(cmd)
        return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps({"body": "b", "title": long, "pull_request": {}}),
                                           stderr="")

    monkeypatch.setattr(mod.subprocess, "run", _run)
    assert mod.main(["7"], ENV) == 0
    edit = next(c for c in calls if "-X" in c)
    new = edit[-1].removeprefix("title=")
    assert len(long) > 100 and len(new) <= 100 and long.startswith(new) and not new.endswith(" ")
    assert mod.short_title("short") == "short"
