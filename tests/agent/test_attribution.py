import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent.parent.parent / "tools"))
import attribution

CC = "_Generated by [Claude Code](https://claude.ai/code)_"
SESSION = "https://claude.ai/code/session_01abc"


def test_footer_after_rule_is_removed():
    assert attribution.remove(f"Closes #1\n\n---\n{CC}") == "Closes #1\n"
    assert attribution.remove(f"Closes #1\n\n---\n{CC}\n") == "Closes #1\n"


def test_session_link_form_is_removed():
    assert attribution.remove(f"Closes #1\n\n{SESSION}\n") == "Closes #1\n"
    assert attribution.remove(f"Closes #1\nClaude-Session: {SESSION}") == "Closes #1\n"
    assert attribution.remove("a\n\nGenerated with Claude Code\n\nCo-Authored-By: Claude <noreply@anthropic.com>") == "a\n"


def test_other_text_is_byte_identical():
    body = "Line one  \r\n\r\n- a\r\n- b\r\n\r\n```\n---\n```\ntail"
    assert attribution.remove(body) == body
    assert attribution.remove(body + f"\r\n\r\n---\r\n{CC}") == body + "\r\n"
    assert attribution.remove(f"a\n{CC}\nb\n---\n") == "a\nb\n---\n"


def test_unrelated_rule_and_human_coauthor_stay():
    body = "x\n\n---\nnotes\nCo-Authored-By: Jane <jane@example.org>"
    assert attribution.remove(body) == body
    assert not attribution.found(body)


def test_found_and_empty():
    assert attribution.found(CC) and attribution.found("claude-session: x") and attribution.found("GENERATED WITH x")
    assert not attribution.found("") and not attribution.found(None)
    assert attribution.remove("") == "" and attribution.remove(None) is None
