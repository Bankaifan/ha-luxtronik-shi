"""Generate docs/registers.md from the register map (run from repo root).

Every row is taken from ``custom_components/luxtronik_shi/registers.py``. The status column reads an
optional ``source`` attribute of a register; the map does not record one per register yet, so every
row says ``open`` until it does. Never edit docs/registers.md by hand.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "custom_components" / "luxtronik_shi"))
import registers  # noqa: E402

OUTPUT = ROOT / "docs" / "registers.md"

KIND_ORDER = {"input": 0, "holding": 1, "discrete": 2}

HEADER = """# Register reference

Generated from `custom_components/luxtronik_shi/registers.py` by `tools/gen_register_docs.py`.
Do not edit this file by hand: run `python tools/gen_register_docs.py` after changing the register map.

* **Type:** Modbus table the register is read from (`input` = input registers, `holding` = holding registers,
  `discrete` = discrete inputs).
* **Scale:** the physical value is the raw value multiplied by this factor.
* **Range:** the allowed range for writable values (`-` if the map does not define one).
* **Status:** the source of the register. `open` means the map does not record a source for it yet.

| Key | Address | Type | Data type | Scale | Unit | Range | Status |
|-----|---------|------|-----------|-------|------|-------|--------|
"""


def _num(value: float) -> str:
    return f"{value:g}"


def _range(reg: registers.Register) -> str:
    if reg.min_value is None and reg.max_value is None:
        return "-"
    if reg.min_value is None:
        return f"≤ {_num(reg.max_value)}"
    if reg.max_value is None:
        return f"≥ {_num(reg.min_value)}"
    return f"{_num(reg.min_value)} … {_num(reg.max_value)}"


def _status(reg: registers.Register) -> str:
    return getattr(reg, "source", None) or "open"


def render() -> str:
    """Return the complete content of docs/registers.md."""
    rows = sorted(registers.ALL_REGISTERS, key=lambda reg: (KIND_ORDER[reg.kind], reg.address, reg.key))
    lines = [
        f"| `{reg.key}` | {reg.address} | {reg.kind} | {reg.dtype} | {_num(reg.scale)} "
        f"| {reg.unit or '-'} | {_range(reg)} | {_status(reg)} |"
        for reg in rows
    ]
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(registers.ALL_REGISTERS)} registers)")


if __name__ == "__main__":
    main()
