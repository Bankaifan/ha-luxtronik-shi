"""Tool/AI attribution footers: the one pattern list and the strip (AGENTS.md, Commits and PRs).

`remove(body)` removes every line that matches a pattern. A `---` separator (and blank lines) that only led up to the
removed footer goes too. Text without a match is returned unchanged, byte for byte.
`found(text)` tells whether a text still carries one (used by tools/check/check_pr_form.py for commit messages and bodies).
"""
import re

# One list for the strip and the check. Matched per line, case-insensitive.
PATTERNS = (
    r"Generated with",
    r"Generated by \[Claude Code\]",
    r"claude\.ai/code",
    r"Claude-Session:",
    # Co-Authored-By trailer of a tool (a human co-author is not touched here).
    r"Co-Authored-By:.*(?:claude|anthropic|copilot|codex|openai|chatgpt|gemini|cursor|aider)",
)
ATTRIBUTION = re.compile("|".join(f"(?:{p})" for p in PATTERNS), re.IGNORECASE)
_LINE = re.compile(r"[^\n]*\n|[^\n]+")


def found(text):
    return bool(ATTRIBUTION.search(text or ""))


def remove(body):
    """Body without attribution lines; the same string when there is none."""
    lines = _LINE.findall(body or "")
    hits = [i for i, line in enumerate(lines) if ATTRIBUTION.search(line)]
    if not hits:
        return body
    last = hits[-1]
    kept = [(i, line) for i, line in enumerate(lines) if i not in hits]

    def trim_blank():
        while kept and kept[-1][0] < last and not kept[-1][1].strip():
            kept.pop()

    trim_blank()
    if kept and kept[-1][0] < last and kept[-1][1].strip() == "---":
        kept.pop()
        trim_blank()
    return "".join(line for _, line in kept)
